#!/usr/bin/env python3
"""Write src/unicode.hpp from Python regex Unicode properties.

The property set is the one tiktoken 0.14.0's regex split agreed with on a
full scalar-value sweep: \\p{L}, \\p{N}, and \\s.
"""

from __future__ import annotations

import argparse
import pathlib
import regex


def build_flags() -> bytearray:
    flags = bytearray(0x110000)
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        value = 0
        if regex.fullmatch(r"\p{L}", ch):
            value |= 1
        if regex.fullmatch(r"\p{N}", ch):
            value |= 2
        if regex.fullmatch(r"\s", ch):
            value |= 4
        flags[cp] = value
    return flags


def render(flags: bytearray) -> str:
    blocks: dict[bytes, int] = {}
    stage: list[int] = []
    blob = bytearray()
    for block_index in range(0x110000 // 256):
        chunk = bytes(flags[block_index * 256 : (block_index + 1) * 256])
        idx = blocks.get(chunk)
        if idx is None:
            idx = len(blocks)
            blocks[chunk] = idx
            blob.extend(chunk)
        stage.append(idx)
    if max(stage) > 0xFFFF:
        raise SystemExit("stage index does not fit in uint16")

    lines = [
        "// Generated by scripts/gen_unicode_tables.py. Do not edit.",
        "// Unicode properties from the Python regex module (Unicode 15.0.0):",
        "// bit 0 letter \\p{L}, bit 1 number \\p{N}, bit 2 whitespace \\s.",
        "// clang-format off",
        "#pragma once",
        "#include <cstdint>",
        "namespace bpe::unicode {",
        "inline constexpr uint8_t kLetter = 1;",
        "inline constexpr uint8_t kNumber = 2;",
        "inline constexpr uint8_t kSpace = 4;",
        "inline constexpr uint32_t kBlockShift = 8;",
        "inline constexpr uint32_t kBlockSize = 256;",
        f"inline constexpr uint16_t kStage1[{len(stage)}] = {{",
    ]
    row: list[str] = []
    for i, value in enumerate(stage):
        row.append(f"{value},")
        if len(row) == 16:
            lines.append("  " + "".join(row))
            row = []
    if row:
        lines.append("  " + "".join(row))
    lines.append("};")
    lines.append(f"inline constexpr uint8_t kBlocks[{len(blob)}] = {{")
    row = []
    for value in blob:
        row.append(f"{value},")
        if len(row) == 32:
            lines.append("  " + "".join(row))
            row = []
    if row:
        lines.append("  " + "".join(row))
    lines.append("};")
    lines.append("inline uint8_t flags(uint32_t cp) noexcept {")
    lines.append("  const uint32_t block = kStage1[cp >> 8];")
    lines.append("  return kBlocks[(block << 8) + (cp & 255u)];")
    lines.append("}")
    lines.append("}  // namespace bpe::unicode")
    lines.append("// clang-format on")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parents[1] / "src" / "unicode.hpp",
    )
    args = parser.parse_args()
    text = render(build_flags())
    args.output.write_text(text)
    print(f"wrote {args.output} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
